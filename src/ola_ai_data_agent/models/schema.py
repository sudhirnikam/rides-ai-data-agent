from pydantic import BaseModel, Field 
from typing import Annotated, Literal
from operator import add

class AgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(..., description="List of messages to be processed by agents")
    user_question: str = Field(..., description="The original question asked by the user")
    curated_ques: str = Field(..., description="Curated Question")
    prompt_query_context: str = Field(..., description="A detailed prompt with SQL DB context which will help agent to generate query")
    is_safe: Literal["Yes", "No"] = Field(..., description="Indicates whether the generated sql is safe to execute or not")
    generated_sql_query: str = Field(..., description="This SQL query is generated by agent based on curated question and prompt context")
    sql_query_result: str =Field(..., description="The result of executing the generated SQL query")
    final_answer: str = Field(..., description="Ther final answer generated by an agent")
    comments: str = Field(..., description="Comments on why the SQL query is safe or not safe to execute")

class JudgeSchema(BaseModel):
    answer: Literal["Yes", "No"] = Field(..., description="Indicates whether the generated SQL query is safe to execute or not")
    comments: str = Field(..., description="Comments on why the SQL query is safe or not safe to execute")
    