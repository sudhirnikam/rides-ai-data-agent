import os 
import sys
from dotenv import load_dotenv

load_dotenv()

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from utils.llm_pick import pick_llm
from models.schema import AgentSchema, JudgeSchema
from utils.database import DatabaseUtil

from langchain_core.messages import HumanMessage, AIMessage

from langgraph.graph import StateGraph, START, END

#------------------------AI Agent Code-------------------

def curate_question(state: AgentSchema) -> AgentSchema:

    user_question = state.user_question

    llm = pick_llm("easy")  # Pick an LLM based on the level of the question

    response = llm.invoke(f"Curate the following question: {user_question}").content.strip()

    state.curated_ques = response

    state.messages = state.messages + [HumanMessage(content=f"{response}")]
    
    return state

def prompt_query_context(state: AgentSchema) -> AgentSchema:

    curated_ques = state.curated_ques

    db_obj = DatabaseUtil({
        "host": os.environ['host'],
        "port": int(os.environ['port']),
        "database": os.environ['database'],
        "user": os.environ['user'],
        "password": os.environ['password'],
    })

    schema_info_context = db_obj.schema_details("public")

    # Constructing the prompt query for the agent to generate the SQL query
    prompt = f"""
    You are an SQL analyst agent. Your task is to convert the user's natural language 
    query into Postgres SQL query that can be executed on the database. You are provided 
    with the user's original query and the schema details of the database, including
    table names, column names, data types, and sample data for each table so that 
    you can understand the structure of the database and generate an accurate SQL query.
    Unless user explicitly asks for specific number of rows, always limit the output to 10 rows.
    Note - Just generate the SQL query without any explanation or additional text because
    this query will be executed directly on the database. So, the output should be SQL
    ready to be executed without any modifications.  
    
    User's Original Query: {curated_ques}

    Database Schema Details:
    {schema_info_context}
    
    """    
    state.prompt_query_context = prompt

    return state

def generate_sql_query(state: AgentSchema) -> AgentSchema:

    prompt = state.prompt_query_context

    llm = pick_llm("hard")  # Pick an LLM based on the level of the question

    response = llm.invoke(prompt, temperature=1).content.strip()

    state.generated_sql_query = response

    state.messages = state.messages + [HumanMessage(content=f"{response}")]
    
    return state

def is_safe_sql(state: AgentSchema) -> AgentSchema:

    sql_query = state.generated_sql_query

    llm = pick_llm("medium")  # Pick an LLM based on the level of the question

    llm_judge = llm.with_structured_output(JudgeSchema)

    prompt = f""" 
    You are an SQL analyst agent. Your task is to determine whether the SQL query generated by another agent is safe to execute on the database. The SQL query should only be used for data retrieval purposes and should not modify the database in any way.  Niether should it contain any potentially harmful operations such as DROP, DELETE, UPDATE, INSERT, or any other commands that could alter the database structure or data. If the SQL query is safe to execute, respond with "Yes" and provide a brief explanation of why it is safe. If the SQL query is not safe to execute, respond with "No" and provide a brief explanation of why it is unsafe.
    Here's the SQL query to evaluate: 
    {sql_query}
    """

    response = llm_judge.invoke(prompt).model_dump()
    state.is_safe = response["answer"]
    state.comments = response["comments"]

    return state

def cancelled_sql(state: AgentSchema) -> AgentSchema:

    comments = state.comments

    state.final_answer = f"The SQL query generated by the agent is not safe to execute. Reason: {comments}. Therefore, the SQL query execution has been cancelled."

    state.messages = state.messages + [AIMessage(content=f"{state.final_answer}")]

    return state

def execute_sql_query(state: AgentSchema) -> AgentSchema:

    sql_query = state.generated_sql_query

    db_obj = DatabaseUtil({
        "host": os.environ['host'],
        "port": int(os.environ['port']),
        "database": os.environ['database'],
        "user": os.environ['user'],
        "password": os.environ['password'],
    })

    result = db_obj.execute_sql(sql_query)

    state.sql_query_result = str(result)

    return state


def represent_final_answer(state: AgentSchema) -> AgentSchema:

    sql_query = state.generated_sql_query
    sql_result = state.sql_query_result
    curated_ques = state.curated_ques

    llm = pick_llm("easy")  # Pick an LLM based on the level of the question

    prompt = f"""
    You are an SQL analyst agent. Your task is to provide a final answer to the user based on the
    execution result of the SQL query and the user's original question. The final answer should be
    concise, clear, and directly address the user's query. Avoid including any SQL code or technical
    details in the final answer. The final answer should be in a user-friendly format that is easy to
    understand. If the execution result is empty or does not provide a clear answer to the user's question, explain this in the final answer. \n
    Here is the execution result: {sql_result} \n
    Here is the user's original question: {curated_ques} \n
    Here is the SQL query that was executed: {sql_query} \n
    """

    response = llm.invoke(prompt).content.strip()

    state.final_answer = response

    state.messages = state.messages + [AIMessage(content=f"{response}")]

    return state


#------------------------Graph Definition-------------------

sql_agent_graph = StateGraph(AgentSchema)

#Nodes
sql_agent_graph.add_node(name="curate_question", node=curate_question)
sql_agent_graph.add_node(name="prompt_query_context", node=prompt_query_context)
sql_agent_graph.add_node(name="generate_sql_query", node=generate_sql_query)
sql_agent_graph.add_node(name="is_safe_sql", node=is_safe_sql)
sql_agent_graph.add_node(name="cancelled_sql", node=cancelled_sql)
sql_agent_graph.add_node(name="execute_sql_query", node=execute_sql_query)
sql_agent_graph.add_node(name="represent_final_answer", node=represent_final_answer)

#Edges
sql_agent_graph.add_edge(START, "curate_question")
sql_agent_graph.add_edge("curate_question", "prompt_query_context")
sql_agent_graph.add_edge("prompt_query_context", "generate_sql_query")
sql_agent_graph.add_edge("generate_sql_query", "is_safe_sql")

#Conditional Edges based on safety check
def is_safe_sql_edge(state: AgentSchema) -> str:
    if state.is_safe.lower() == "yes":
        return "execute_sql_query"
    else:
        return "cancelled_sql"

sql_agent_graph.add_conditional_edges("is_safe_sql", is_safe_sql_edge, path_map={
        "execute_sql_query": "execute_sql_query",
        "cancelled_sql": "cancelled_sql",
    },)

